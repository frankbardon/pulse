// pipeSetSamples constructs minSampleRows rows where the "issuers"
// column carries 2 pipe-delimited tokens per cell — every cell hits
// the heuristic. Other columns stay scalar so the heuristic does not
// fire on them.
func pipeSetSamples() *mockReader {
	rows := make([][]string, 0, minSampleRows)
	pairs := []string{"VISA|MC", "AMEX|DISC", "VISA|AMEX", "MC|DISC"}
	categories := []string{"A", "B", "C"}
	for i := 0; i < minSampleRows; i++ {
		// id column repeats (categorical) — so the "all unique
		// cells" guard does not fire on it.
		rows = append(rows, []string{
			categories[i%len(categories)],
			pairs[i%len(pairs)],
		})
	}
	return newMockReader([]string{"id", "issuers"}, rows)
}

func itoa(i int) string {
	if i == 0 {
		return "0"
	}
	var buf [20]byte
	pos := len(buf)
	for i > 0 {
		pos--
		buf[pos] = byte('0' + i%10)
		i /= 10
	}
	return string(buf[pos:])
}

func TestInfer_SetFromPipeDelimitedCSV(t *testing.T) {
	r := pipeSetSamples()
	res, err := InferSchemaWithOptions(r, InferOptions{})
	if err != nil {
		t.Fatalf("InferSchemaWithOptions: %v", err)
	}
	if got := res.Schema.Field("issuers").Type; got != encoding.FieldTypeSetU8 {
		t.Errorf("issuers type = %s, want set_u8", got)
	}
	if d := res.Delimiters["issuers"]; d != "|" {
		t.Errorf("delimiter = %q, want |", d)
	}
}

