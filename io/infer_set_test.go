func TestConvertValue_SetU8(t *testing.T) {
	dict := encoding.NewDictionary()
	for _, v := range []string{"VISA", "MC", "AMEX", "DISC"} {
		if _, err := dict.Add(v); err != nil {
			t.Fatalf("dict.Add: %v", err)
		}
	}
	cases := []struct {
		raw  string
		want uint64
	}{
		{"VISA|MC", 0b0011},
		{"AMEX", 0b0100},
		{"AMEX|VISA", 0b0101},
		{"DISC|MC|VISA", 0b1011},
		{"", 0}, // empty cell → empty mask
	}
	for _, c := range cases {
		got, err := convertValue(c.raw, encoding.FieldTypeSetU8, dict, "|")
		if err != nil {
			t.Errorf("convertValue %q: %v", c.raw, err)
			continue
		}
		if got != c.want {
			t.Errorf("convertValue %q = 0b%b, want 0b%b", c.raw, got, c.want)
		}
	}
}

func TestConvertValue_SetU8_OverflowEmitsTypedError(t *testing.T) {
	dict := encoding.NewDictionary()
	// Push 8 tokens — set_u8 capacity is exactly 8. The 9th token
	// must trip PULSE_IMPORT_SET_OVERFLOW.
	for i := 0; i < 8; i++ {
		if _, err := dict.Add("T" + itoa(i)); err != nil {
			t.Fatalf("dict.Add: %v", err)
		}
	}
	_, err := convertValue("T8", encoding.FieldTypeSetU8, dict, "|")
	if err == nil {
		t.Fatal("expected overflow error")
	}
	if !strings.Contains(err.Error(), "PULSE_IMPORT_SET_OVERFLOW") &&
		!strings.Contains(err.Error(), "overflowed") {
		t.Errorf("error = %v, want PULSE_IMPORT_SET_OVERFLOW", err)
	}
}
