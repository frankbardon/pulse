package integration_test

import (
	"bytes"
	"os"
	"sync"
	"testing"

	"github.com/spf13/afero"

	"github.com/frankbardon/pulse/internal/doccheck"
	"github.com/frankbardon/pulse/internal/doccoverage"
)

// docsCoverageEnv are the variables `make docs` clears so a developer's
// .env cannot perturb the generated pages (the Makefile's DOCS_GUIDE_ENV).
var docsCoverageEnv = []string{"PULSE_LABEL_TABLES_DIR", "PULSE_RANGE_TABLES_DIR", "PULSE_LOOKUP_TABLES_DIR",
	"PULSE_POPULATIONS_DIR", "PULSE_TEMPLATES_DIR", "PULSE_FEATURE_PROFILE"}

// docsCoverage builds the matrix once per test binary: both gates read the
// same build (each clears the environment first, so whichever runs first
// builds it under the `make docs` environment).
var docsCoverage struct {
	once sync.Once
	m    *doccoverage.Matrix
	err  error
}

func buildDocsCoverage(t *testing.T) *doccoverage.Matrix {
	t.Helper()
	for _, k := range docsCoverageEnv {
		t.Setenv(k, "")
	}
	docsCoverage.once.Do(func() {
		docsCoverage.m, docsCoverage.err = doccoverage.BuildFrom(afero.NewOsFs())
	})
	if docsCoverage.err != nil {
		t.Fatal(docsCoverage.err)
	}
	return docsCoverage.m
}

// TestDocsCoverageCurrent keeps the generated coverage matrix
// (docs/src/contract/coverage.md) current: it rebuilds the page from the
// sources of truth and requires the committed page to match byte for byte.
// A new public symbol, leaf, flag, tool, operator, code or env var — or a
// doc edit that changes a cell — without `make docs` fails here.
func TestDocsCoverageCurrent(t *testing.T) {
	// serial: t.Setenv mutates the process environment
	want := buildDocsCoverage(t).Render()
	got, err := os.ReadFile(doccoverage.PagePath)
	if err != nil {
		t.Fatalf("%v: run `make docs` and commit %s", err, doccoverage.PagePath)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale: run `make docs` and commit it (never hand-edit it; it is generated by internal/doccoverage)", doccoverage.PagePath)
	}
}

// TestDocsCoverageNoGaps fails on a required coverage cell that is empty
// (a gap) unless the shrink-only allowlist
// internal/doccheck/allowlists/coverage.txt names it, and on an allowlist
// entry whose gap has been closed. Keys are (row kind, "<identifier>
// <surface>").
func TestDocsCoverageNoGaps(t *testing.T) {
	// serial: t.Setenv mutates the process environment
	m := buildDocsCoverage(t)
	fsys := afero.NewOsFs()
	allow, err := doccheck.Load(fsys, doccheck.AllowlistFile(doccoverage.AllowlistName))
	if err != nil {
		t.Fatal(err)
	}
	gaps := m.Gaps()
	if len(m.Lines) < 1000 {
		t.Fatalf("only %d coverage rows — a source is broken", len(m.Lines))
	}
	for _, p := range allow.Reconcile(gaps).Problems(allow.File) {
		t.Error(p)
	}
}
