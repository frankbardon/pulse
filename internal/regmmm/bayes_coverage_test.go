// bayes_coverage_test.go is REG_MMM_BAYES's calibration study
// (bayesian-mmm E4-S1): a single-seed pass bar can pass by luck, so this
// fits coverageReplicates (50) fresh draws of the joint-truth scenario
// (mmmfixture.JointWithSeed: the same channels, curves, controls and
// noise, new spend / price / promo / noise per replicate) with the
// default slot and records, per channel, whether the true ROI and the
// true contribution (summed over every week) fall inside the default
// 90% credible intervals. It reports the empirical coverage per channel
// and overall, the median runtime per fit, and writes the whole report
// to testdata/coverage-study.md — the committed results file.
//
// The study itself (TestMMMBayes_CoverageStudy,
// bayes_coverage_study_test.go) is behind the mmmcoverage build tag —
// never in `go test ./...` or CI (about 32 s per fit on
// arm64). Reproduce with coverageCommand. This file's summary and
// report arithmetic is untagged and pinned by
// TestMMMBayes_CoverageSummary.
//
// The bar: overall ROI coverage and overall contribution coverage
// (replicates × channels each) inside [coverageBandLow,
// coverageBandHigh]. A miss is reported in the file and fails the test;
// never loosen the band — tune priors / defaults instead.

const (
	// coverageDataSeed0 is the first replicate's data seed; replicate i
	// draws mmmfixture.JointWithSeed(coverageDataSeed0 + i), clear of the
	// pass bar's JointSeed.
	coverageDataSeed0 = 1001
	coverageLevel     = 0.9
	coverageBandLow   = 0.80
	coverageBandHigh  = 0.98
	coverageCommand   = "go test -count=1 -tags mmmcoverage -run TestMMMBayes_CoverageStudy -timeout 3h -v ./internal/regmmm/ -mmm.coverage-workers 2"
)

// coverageRep is one replicate's record.
type coverageRep struct {
	dataSeed, rngSeed uint64
	elapsed           time.Duration
	failed            string
	// per channel, JointChannels order
	roiIn, contribIn []bool
	roiErr           []float64 // posterior-median ROI relative error
	roiWidth         []float64 // interval width over the true ROI
	maxRHat, minESS  float64
	divergences      int
	warnings         []string
}

// coverageSummary is the study's aggregate.
type coverageSummary struct {
	roi, contrib           []int // covered replicates per channel
	roiAll, contribAll     int
	trials                 int // replicates × channels
	failed, warned         int
	medianFit, minFit, max time.Duration
	pass                   bool
}

func summarizeCoverage(reps []coverageRep) coverageSummary {
	nc := len(mmmfixture.JointChannels)
	s := coverageSummary{roi: make([]int, nc), contrib: make([]int, nc), trials: len(reps) * nc}
	times := make([]time.Duration, 0, len(reps))
	for _, r := range reps {
		times = append(times, r.elapsed)
		if r.failed != "" {
			s.failed++ // a failed fit covers nothing
			continue
		}
		if len(r.warnings) > 0 {
			s.warned++
		}
		for ci := range nc {
			if r.roiIn[ci] {
				s.roi[ci]++
				s.roiAll++
			}
			if r.contribIn[ci] {
				s.contrib[ci]++
				s.contribAll++
			}
		}
	}
	slices.Sort(times)
	if n := len(times); n > 0 {
		s.minFit, s.max = times[0], times[n-1]
		s.medianFit = times[n/2]
		if n%2 == 0 {
			s.medianFit = (times[n/2-1] + times[n/2]) / 2
		}
	}
	inBand := func(k int) bool {
		f := float64(k) / float64(s.trials)
		return s.trials > 0 && f >= coverageBandLow && f <= coverageBandHigh
	}
	s.pass = inBand(s.roiAll) && inBand(s.contribAll)
	return s
}

// binomialSE is the standard error of an empirical coverage over n
// trials at the nominal level.
func binomialSE(n int) float64 {
	if n <= 0 {
		return math.NaN()
	}
	return math.Sqrt(coverageLevel * (1 - coverageLevel) / float64(n))
}

func pct(k, n int) string { return fmt.Sprintf("%.1f%% (%d/%d)", 100*float64(k)/float64(n), k, n) }

// coverageReport renders the results file.
func coverageReport(reps []coverageRep, s coverageSummary, wall time.Duration, workers int) []byte {
	var b bytes.Buffer
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	verdict := "MISS"
	if s.pass {
		verdict = "PASS"
	}
	n := len(reps)
	w("# REG_MMM_BAYES coverage study\n\n")
	w("Generated by `TestMMMBayes_CoverageStudy` (`internal/regmmm/bayes_coverage_study_test.go`, build tag `mmmcoverage`; report in `bayes_coverage_test.go`); never hand-edit. Reproduce with:\n\n")
	w("```sh\n%s\n```\n\n", coverageCommand)
	w("## Design\n\n")
	w("- %d replicates of the joint-truth scenario: replicate i fits `mmmfixture.JointWithSeed(%d + i)` (fresh spend, price, promo and noise over the same channels, curves and controls; 156 weeks, 4 channels) with `rng_seed` i + 1.\n", n, coverageDataSeed0)
	w("- Each fit is the default `REG_MMM_BAYES` slot (default priors; %d chains × (%d warmup + %d draws); every week; no holdout).\n", mcmc.DefaultChains, mcmc.DefaultWarmup, mcmc.DefaultDraws)
	w("- Per channel: is the true ROI (summed true contribution over summed spend) inside `outputs.roi.<channel>` [lower, upper], and the true contribution (summed over every week) inside `outputs.contribution.<channel>`, at the default %.0f%% credible level. A failed fit covers nothing. Spend is data, not a parameter, so each ROI draw is that channel's contribution draw over a fixed summed spend: the two intervals cover together or miss together, and the two columns below agree by construction.\n", 100*coverageLevel)
	w("- Bar: overall ROI coverage and overall contribution coverage each in [%.0f%%, %.0f%%]. The binomial standard error at 90%% nominal is %.1f points overall (%d trials) and %.1f points per channel (%d replicates).\n\n", 100*coverageBandLow, 100*coverageBandHigh, 100*binomialSE(s.trials), s.trials, 100*binomialSE(n), n)
	w("## Result: %s\n\n", verdict)
	w("| | ROI coverage | Contribution coverage |\n|---|---|---|\n")
	w("| **overall** | **%s** | **%s** |\n", pct(s.roiAll, s.trials), pct(s.contribAll, s.trials))
	for ci, c := range mmmfixture.JointChannels {
		w("| %s | %s | %s |\n", c.Name, pct(s.roi[ci], n), pct(s.contrib[ci], n))
	}
	w("\n| channel | mean median-ROI error | mean \\|median-ROI error\\| | mean 90%% width / true ROI |\n|---|---|---|---|\n")
	for ci, c := range mmmfixture.JointChannels {
		e, a, wd, k := 0.0, 0.0, 0.0, 0
		for _, r := range reps {
			if r.failed != "" {
				continue
			}
			e += r.roiErr[ci]
			if r.roiErr[ci] < 0 {
				a -= r.roiErr[ci]
			} else {
				a += r.roiErr[ci]
			}
			wd += r.roiWidth[ci]
			k++
		}
		if k > 0 {
			w("| %s | %+.2f%% | %.2f%% | %.1f%% |\n", c.Name, 100*e/float64(k), 100*a/float64(k), 100*wd/float64(k))
		}
	}
	w("\n## Runtime and sampler health\n\n")
	w("- Median fit %.1f s (min %.1f s, max %.1f s); study wall time %s with %d concurrent fit(s) on %s/%s, GOMAXPROCS %d.\n",
		s.medianFit.Seconds(), s.minFit.Seconds(), s.max.Seconds(), wall.Round(time.Second), workers, runtime.GOOS, runtime.GOARCH, runtime.GOMAXPROCS(0))
	w("- Failed fits: %d. Fits with a warning: %d.\n\n", s.failed, s.warned)
	w("## Replicates\n\n")
	w("| # | data seed | rng_seed | ROI in (tv/search/social/display) | contribution in | max R̂ | min bulk ESS | divergences | warnings | fit |\n|---|---|---|---|---|---|---|---|---|---|\n")
	mark := func(in []bool) string {
		out := make([]string, len(in))
		for i, v := range in {
			out[i] = "-"
			if v {
				out[i] = "y"
			}
		}
		return strings.Join(out, "/")
	}
	for i, r := range reps {
		if r.failed != "" {
			w("| %d | %d | %d | FAILED: %s | | | | | | %.1f s |\n", i, r.dataSeed, r.rngSeed, strings.ReplaceAll(r.failed, "|", "\\|"), r.elapsed.Seconds())
			continue
		}
		warn := strings.Join(r.warnings, ", ")
		if warn == "" {
			warn = "none"
		}
		w("| %d | %d | %d | %s | %s | %.4f | %.0f | %d | %s | %.1f s |\n", i, r.dataSeed, r.rngSeed, mark(r.roiIn), mark(r.contribIn), r.maxRHat, r.minESS, r.divergences, warn, r.elapsed.Seconds())
	}
	return b.Bytes()
}

// TestMMMBayes_CoverageSummary pins the study's arithmetic on a
// synthetic record set (no fit): per-channel and overall counts, a
// failed fit covering nothing, the median runtime and both band edges.
func TestMMMBayes_CoverageSummary(t *testing.T) {
	nc := len(mmmfixture.JointChannels)
	rep := func(sec int, roi, contrib bool) coverageRep {
		r := coverageRep{elapsed: time.Duration(sec) * time.Second, roiIn: make([]bool, nc), contribIn: make([]bool, nc),
			roiErr: make([]float64, nc), roiWidth: make([]float64, nc)}
		for ci := range nc {
			r.roiIn[ci], r.contribIn[ci] = roi, contrib
		}
		return r
	}
	// 10 replicates: 9 fully covered, 1 failed → 90% both, a pass.
	var reps []coverageRep
	for i := range 9 {
		reps = append(reps, rep(10+i, true, true))
	}
	failed := rep(100, true, true)
	failed.failed = "boom"
	reps = append(reps, failed)
	s := summarizeCoverage(reps)
	if s.trials != 10*nc || s.roiAll != 9*nc || s.contribAll != 9*nc || s.failed != 1 || !s.pass {
		t.Errorf("summary %+v: want %d trials, %d covered each, 1 failed, a pass", s, 10*nc, 9*nc)
	}
	if s.roi[0] != 9 || s.contrib[nc-1] != 9 {
		t.Errorf("per-channel %v / %v, want 9", s.roi, s.contrib)
	}
	if s.medianFit != 14500*time.Millisecond || s.minFit != 10*time.Second || s.max != 100*time.Second {
		t.Errorf("runtime median %v min %v max %v, want 14.5s 10s 100s", s.medianFit, s.minFit, s.max)
	}
	// Every replicate covered: 100% > 98%, a miss on the upper edge.
	all := []coverageRep{rep(1, true, true), rep(1, true, true)}
	if s := summarizeCoverage(all); s.pass {
		t.Error("100% coverage passed: want a miss above the band")
	}
	// 4 of 5 ROI-covered (80%: the lower edge, in band), contribution 3 of 5 (a miss).
	edge := []coverageRep{rep(1, true, true), rep(1, true, true), rep(1, true, true), rep(1, true, false), rep(1, false, false)}
	if s := summarizeCoverage(edge); s.pass || s.roiAll != 4*nc || s.contribAll != 3*nc {
		t.Errorf("edge summary %+v: want ROI 80%% (in band), contribution 60%%, a miss", s)
	}
	// Both at the 80% lower edge: in band.
	edge[3] = rep(1, true, true)
	if s := summarizeCoverage(edge); !s.pass {
		t.Errorf("edge summary %+v: 80%% on both is in band, want a pass", s)
	}
	if !bytes.Contains(coverageReport(reps, s, time.Minute, 1), []byte("## Result: PASS")) {
		t.Error("the report does not state the verdict")
	}
}
