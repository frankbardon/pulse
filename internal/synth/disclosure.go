// The disclosure section (FR-21, #368): how close the twin sits to real
// records. A twin carries NO formal privacy guarantee; these are the
// figures a data owner reads before sharing one.
//
// # What is measured
//
//   - exact_matches / exact_match_rate: the generated rows whose value on
//     EVERY output column equals some source row's (null equal to null),
//     over ALL generated rows — a hash lookup, so it needs no sample.
//   - dcr_median / dcr_p5: each SAMPLED generated row's Gower distance to
//     its closest source record, summarised by the median and the 5th
//     percentile (type-7 interpolation). An exact copy has distance 0.
//
// # The Gower distance
//
// The mean over every output column (the tag column excluded) of a
// per-column distance in [0, 1]:
//
//   - integers, floats, decimal128, u4, date and datetime: |a - b| / range,
//     range = max - min over the SOURCE rows, clamped at 1; a zero range
//     scores 0 for equal values and 1 otherwise; NaN equals only NaN;
//   - categorical and packed_bool: 0 when equal, else 1;
//   - set_*: the Jaccard distance |A xor B| / |A or B| (0 for two empty
//     selections);
//   - vec_*: the mean of the per-element numeric distances, each element
//     with its own source range;
//   - null: 0 when both are null, 1 when one is.
//
// # Determinism
//
// Every figure is a pure function of the tagged cohort, the seed and the
// sample cap. The sample is drawn from its own counter-based stream
// (disclosureSampleDomain), never the generation RNG, so turning the
// section on or off moves no generated byte. Each distance sums its
// columns in schema order and only adds or divides — no product feeds an
// add, so nothing can contract into a fused multiply-add — and each
// sampled row's minimum is independent of the others, so the worker
// count cannot move a bit.

// DefaultDisclosureSample is the disclosure sample cap when
// Options.DisclosureSample is 0: the generated rows the DCR is measured
// over.
const DefaultDisclosureSample = 10_000

// disclosureSampleDomain separates the disclosure sample stream from
// every other counter-based stream derived from the same seed.
const disclosureSampleDomain uint64 = 0x444953434C4F5345 // "DISCLOSE"

// DisclosureDistanceGower is DisclosureFidelity.Distance's one value.
const DisclosureDistanceGower = "gower"

// DisclosureFidelity is FidelityReport.Disclosure: the twin's closeness
// to real records. See the package note above for every definition.
type DisclosureFidelity struct {
	// Distance names the record distance: "gower".
	Distance string `json:"distance"`
	// Columns is the number of output columns compared (the tag column
	// is not one).
	Columns int `json:"columns"`
	// SourceRows and SyntheticRows are the partitions' sizes.
	SourceRows    int `json:"source_rows"`
	SyntheticRows int `json:"synthetic_rows"`
	// ExactMatches counts the generated rows equal to some source row on
	// every column; ExactMatchRate is it over SyntheticRows.
	ExactMatches   int     `json:"exact_matches"`
	ExactMatchRate float64 `json:"exact_match_rate"`
	// SampleRows is the number of generated rows the distance to closest
	// record was measured over: every generated row, or the seeded
	// sample when there are more than the cap.
	SampleRows int `json:"sample_rows"`
	// DCRMedian and DCRP5 are the median and 5th percentile of the
	// sampled rows' Gower distance to their closest source record, in
	// [0, 1]. Zero-valued and meaningless when Error is set.
	DCRMedian float64 `json:"dcr_median"`
	DCRP5     float64 `json:"dcr_p5"`
	// Error is set instead of the distance figures when the section
	// cannot be computed (a source with no rows).
	Error string `json:"error,omitempty"`
}

// disclosureSampleCap resolves Options.DisclosureSample: 0 is the
// default, a negative value is refused.
func disclosureSampleCap(opts Options) (int, error) {
	switch {
	case opts.DisclosureSample < 0:
		return 0, errors.NewCodedErrorWithDetails(errors.SERVICE_VALIDATION,
			"disclosure sample must be 0 (the default, 10000) or a positive row count",
			map[string]any{"disclosure_sample": opts.DisclosureSample})
	case opts.DisclosureSample == 0:
		return DefaultDisclosureSample, nil
	}
	return opts.DisclosureSample, nil
}

// DisclosureEnabled reports whether a run writes the disclosure section:
// a fidelity report against a source, not switched off.
func DisclosureEnabled(opts Options) bool {
	return opts.SourceCohort != "" && opts.FidelityReportPath != "" && !opts.DisableDisclosure
}

// CheckDisclosureBudget is the disclosure pass's pre-flight, run before
// generation so an over-budget run writes nothing: it charges the pass's
// working set (DisclosureMemoryEstimate) against l's MaxEstimatedMemory
// and refuses with PULSE_LIMIT_EXCEEDED when it does not fit. It reads
// the source's header and schema only. A negative opts.DisclosureSample
// is refused SERVICE_VALIDATION. A source that cannot be read is left to
// generation, which refuses it with its own code.
func CheckDisclosureBudget(fs afero.Fs, spec *Spec, opts Options, l limits.Limits) error {
	sample, err := disclosureSampleCap(opts)
	if err != nil {
		return err
	}
	if !DisclosureEnabled(opts) || fs == nil || spec == nil {
		return nil
	}
	f, err := fs.Open(opts.SourceCohort)
	if err != nil {
		return nil
	}
	defer f.Close()
	version, err := encoding.ReadHeader(f)
	if err != nil {
		return nil
	}
	schema, err := encoding.ReadSchema(f, version)
	if err != nil {
		return nil
	}
	start, err := f.Seek(0, io.SeekCurrent)
	if err != nil {
		return nil
	}
	end, err := f.Seek(0, io.SeekEnd)
	if err != nil {
		return nil
	}
	sourceRows, _, ok := schema.RecordCountForPayload(end - start)
	if !ok {
		return nil
	}
	est := DisclosureMemoryEstimate(schema, sourceRows, int64(spec.RowCount), sample)
	if ce := limits.Check(l, limits.MaxEstimatedMemory, est); ce != nil {
		return ce
	}
	return nil
}

// DisclosureMemoryEstimate is the disclosure pass's working set in bytes,
// an upper bound: every source row decoded into its distance slots plus
// its exact-match key and map entry, and every sampled generated row's
// slots, index and distance. schema is the output's column layout (a
// tag column, if present, is not counted).
func DisclosureMemoryEstimate(schema *encoding.Schema, sourceRows, syntheticRows int64, sample int) int64 {
	var rowBytes, keyBytes int64
	for i := range schema.Fields {
		f := &schema.Fields[i]
		if f.Name == SyntheticFieldName {
			continue
		}
		rowBytes++ // null flag
		keyBytes++
		switch {
		case f.Type.IsSet():
			rowBytes += 8 * encoding.SetMaskWords
			keyBytes += 8 * encoding.SetMaskWords
		case f.Type.IsVector():
			dim := int64(schema.VectorDim(i))
			rowBytes += 8 * dim
			keyBytes += 8 * dim
		case f.Type.IsDecimal():
			rowBytes += 8
			keyBytes += 41 // sign, 38 digits, point, length byte
		default:
			rowBytes += 8
			keyBytes += 8
		}
	}
	const mapEntryOverhead = 64 // string header, bucket slot, hash
	sampled := syntheticRows
	if int64(sample) < sampled {
		sampled = int64(sample)
	}
	return sourceRows*(rowBytes+keyBytes+mapEntryOverhead) + sampled*(rowBytes+16)
}

type disclosureKind uint8

const (
	disclosureNumeric disclosureKind = iota
	disclosureNominal
	disclosureSet
	disclosureVector
)

// disclosureColumn is one output column's distance plan.
type disclosureColumn struct {
	field int
	kind  disclosureKind
	slot  int // first float slot (numeric, nominal, vector)
	width int // float slots (dim for a vector, else 1)
	set   int // set slot (set only)
	exact bool
}

// disclosurePlan lays the output columns out into a row's float and set
// slots.
type disclosurePlan struct {
	schema *encoding.Schema
	cols   []disclosureColumn
	slots  int
	sets   int
	ranges []float64 // per float slot, over the source rows
}

func newDisclosurePlan(schema *encoding.Schema) *disclosurePlan {
	p := &disclosurePlan{schema: schema}
	for i := range schema.Fields {
		f := &schema.Fields[i]
		if f.Name == SyntheticFieldName {
			continue
		}
		c := disclosureColumn{field: i, slot: p.slots, width: 1}
		switch {
		case f.Type.IsSet():
			c.kind, c.width, c.set = disclosureSet, 0, p.sets
			p.sets++
		case f.Type.IsVector():
			c.kind, c.width = disclosureVector, schema.VectorDim(i)
		case f.Type.IsCategorical() || f.Type == encoding.FieldTypePackedBool:
			c.kind = disclosureNominal
		default:
			c.kind = disclosureNumeric
			c.exact = f.Type == encoding.FieldTypeU64
		}
		p.slots += c.width
		p.cols = append(p.cols, c)
	}
	return p
}

// disclosureRows is a block of decoded rows, row-major.
type disclosureRows struct {
	vals  []float64
	nulls []bool
	sets  []encoding.SetMask
	n     int
}

// exactWords is the ExactU64Record sink for one decoded row.
type exactWords map[int]uint64

func (w exactWords) SetExactU64At(idx int, v uint64) { w[idx] = v }

// disclosureDecoder decodes the tagged cohort row by row into slots and
// exact-match keys.
type disclosureDecoder struct {
	plan   *disclosurePlan
	rr     *encx.RecordReader
	exact  *encx.ExactU64Words
	words  exactWords
	values map[string]float64
	nulls  map[string]bool
	wide   map[string]any
	key    []byte
}

func newDisclosureDecoder(plan *disclosurePlan, records []byte) *disclosureDecoder {
	d := &disclosureDecoder{
		plan:   plan,
		rr:     encx.NewRecordReader(bytes.NewReader(records), plan.schema),
		exact:  encx.NewExactU64Words(plan.schema),
		words:  exactWords{},
		values: make(map[string]float64, len(plan.schema.Fields)),
		nulls:  make(map[string]bool, len(plan.schema.Fields)),
		wide:   make(map[string]any, len(plan.schema.Fields)),
	}
	d.rr.CaptureExactU64(d.exact)
	return d
}

// next decodes one row; false at the end of the records.
func (d *disclosureDecoder) next() (synthetic bool, ok bool) {
	if err := d.rr.ReadRecordWithWide(d.values, d.nulls, d.wide); err != nil {
		return false, false
	}
	clear(d.words)
	d.exact.ApplyTo(d.words)
	return d.values[SyntheticFieldName] != 0, true
}

// rowKey is the decoded row's exact-match key: per column a null flag
// then the stored value — the exact word for u64, the decimal's digits,
// the set's mask words, a vector's element bits, else the float bits.
func (d *disclosureDecoder) rowKey() string {
	k := d.key[:0]
	for _, c := range d.plan.cols {
		f := &d.plan.schema.Fields[c.field]
		if d.nulls[f.Name] {
			k = append(k, 0)
			continue
		}
		k = append(k, 1)
		switch {
		case c.kind == disclosureSet:
			for _, w := range setMaskFromWide(d.wide[f.Name]).Words() {
				k = binary.LittleEndian.AppendUint64(k, w)
			}
		case c.kind == disclosureVector:
			v, _ := d.wide[f.Name].([]float64)
			for e := 0; e < c.width; e++ {
				var x float64
				if e < len(v) {
					x = v[e]
				}
				k = binary.LittleEndian.AppendUint64(k, math.Float64bits(x))
			}
		case f.Type.IsDecimal():
			s := ""
			if dv, ok := d.wide[f.Name].(encoding.Decimal128); ok {
				s = dv.String(f.Scale)
			}
			k = append(k, byte(len(s)))
			k = append(k, s...)
		case c.exact:
			k = binary.LittleEndian.AppendUint64(k, d.words[c.field])
		default:
			k = binary.LittleEndian.AppendUint64(k, math.Float64bits(d.values[f.Name]))
		}
	}
	d.key = k
	return string(k)
}

// appendRow copies the decoded row into rows' slots.
func (d *disclosureDecoder) appendRow(rows *disclosureRows) {
	p := d.plan
	for _, c := range p.cols {
		f := &p.schema.Fields[c.field]
		isNull := d.nulls[f.Name]
		rows.nulls = append(rows.nulls, isNull)
		switch c.kind {
		case disclosureSet:
			m := encoding.SetMask{}
			if !isNull {
				m = setMaskFromWide(d.wide[f.Name])
			}
			rows.sets = append(rows.sets, m)
		case disclosureVector:
			v, _ := d.wide[f.Name].([]float64)
			for e := 0; e < c.width; e++ {
				var x float64
				if !isNull && e < len(v) {
					x = v[e]
				}
				rows.vals = append(rows.vals, x)
			}
		default:
			rows.vals = append(rows.vals, d.values[f.Name])
		}
	}
	rows.n++
}

// BuildDisclosure adds the disclosure section to report from the tagged
// cohort (mergedSchema, records): exact matches over every generated row
// and the Gower distance to closest record over a seeded sample of at
// most opts.DisclosureSample generated rows (DefaultDisclosureSample when
// 0). Nothing is added when DisclosureEnabled(opts) is false. Every
// figure is deterministic in (records, opts.Seed, the sample cap).
func BuildDisclosure(report *FidelityReport, mergedSchema *encoding.Schema, records []byte, opts Options) error {
	if !DisclosureEnabled(opts) {
		return nil
	}
	sample, err := disclosureSampleCap(opts)
	if err != nil {
		return err
	}
	report.Disclosure = computeDisclosure(mergedSchema, records, opts.Seed, sample, runtime.GOMAXPROCS(0))
	return nil
}

// computeDisclosure is BuildDisclosure's body, its worker count explicit
// so a test can prove it moves no bit.
func computeDisclosure(schema *encoding.Schema, records []byte, seed int64, sample, workers int) *DisclosureFidelity {
	plan := newDisclosurePlan(schema)
	out := &DisclosureFidelity{Distance: DisclosureDistanceGower, Columns: len(plan.cols)}

	// Pass 1: the source rows, their keys and their per-slot ranges.
	src := &disclosureRows{}
	keys := make(map[string]struct{})
	dec := newDisclosureDecoder(plan, records)
	for {
		synthetic, ok := dec.next()
		if !ok {
			break
		}
		if synthetic {
			out.SyntheticRows++
			continue
		}
		keys[dec.rowKey()] = struct{}{}
		dec.appendRow(src)
	}
	out.SourceRows = src.n
	plan.ranges = sourceRanges(plan, src)

	// Pass 2: exact matches over every generated row, and the sampled
	// rows' slots.
	picked := disclosureSampleOrdinals(out.SyntheticRows, sample, seed)
	syn := &disclosureRows{}
	dec = newDisclosureDecoder(plan, records)
	ordinal, next := 0, 0
	for {
		synthetic, ok := dec.next()
		if !ok {
			break
		}
		if !synthetic {
			continue
		}
		if _, hit := keys[dec.rowKey()]; hit {
			out.ExactMatches++
		}
		if next < len(picked) && picked[next] == ordinal {
			dec.appendRow(syn)
			next++
		}
		ordinal++
	}
	if out.SyntheticRows > 0 {
		out.ExactMatchRate = float64(out.ExactMatches) / float64(out.SyntheticRows)
	}
	out.SampleRows = syn.n
	if src.n == 0 {
		out.Error = "the source cohort has no rows to measure a distance to"
		return out
	}
	if syn.n == 0 {
		out.Error = "no generated row to measure a distance from"
		return out
	}

	dcr := closestDistances(plan, src, syn, workers)
	sort.Float64s(dcr)
	out.DCRMedian = disclosureQuantile(dcr, 0.5)
	out.DCRP5 = disclosureQuantile(dcr, 0.05)
	return out
}

// sourceRanges is every float slot's max - min over the source rows'
// non-null, non-NaN values (0 when there is none).
func sourceRanges(plan *disclosurePlan, src *disclosureRows) []float64 {
	lo := make([]float64, plan.slots)
	hi := make([]float64, plan.slots)
	seen := make([]bool, plan.slots)
	for r := 0; r < src.n; r++ {
		vals := src.vals[r*plan.slots : (r+1)*plan.slots]
		nulls := src.nulls[r*len(plan.cols) : (r+1)*len(plan.cols)]
		for ci, c := range plan.cols {
			if nulls[ci] || c.kind == disclosureSet || c.kind == disclosureNominal {
				continue
			}
			for s := c.slot; s < c.slot+c.width; s++ {
				x := vals[s]
				if math.IsNaN(x) {
					continue
				}
				if !seen[s] {
					lo[s], hi[s], seen[s] = x, x, true
					continue
				}
				lo[s] = math.Min(lo[s], x)
				hi[s] = math.Max(hi[s], x)
			}
		}
	}
	out := make([]float64, plan.slots)
	for s := range out {
		if seen[s] {
			out[s] = hi[s] - lo[s]
		}
	}
	return out
}

// numericDistance is one float slot's Gower term.
func numericDistance(a, b, r float64) float64 {
	if a == b {
		return 0
	}
	if math.IsNaN(a) || math.IsNaN(b) {
		if math.IsNaN(a) && math.IsNaN(b) {
			return 0
		}
		return 1
	}
	if r == 0 || math.IsInf(r, 0) || math.IsNaN(r) {
		return 1
	}
	d := math.Abs(a-b) / r
	if d > 1 || math.IsNaN(d) {
		return 1
	}
	return d
}

// jaccardDistance is a set column's Gower term.
func jaccardDistance(a, b encoding.SetMask) float64 {
	union := a.Union(b).PopCount()
	if union == 0 {
		return 0
	}
	return float64(union-a.Intersect(b).PopCount()) / float64(union)
}

// closestDistances returns each sampled row's Gower distance to its
// closest source row, in sample order. Rows are split across workers;
// each row's minimum depends on that row alone, so the split moves no
// bit.
func closestDistances(plan *disclosurePlan, src, syn *disclosureRows, workers int) []float64 {
	out := make([]float64, syn.n)
	if workers < 1 {
		workers = 1
	}
	if workers > syn.n {
		workers = syn.n
	}
	var wg sync.WaitGroup
	chunk := (syn.n + workers - 1) / workers
	for w := 0; w < workers; w++ {
		lo, hi := w*chunk, (w+1)*chunk
		if hi > syn.n {
			hi = syn.n
		}
		if lo >= hi {
			break
		}
		wg.Add(1)
		go func(lo, hi int) {
			defer wg.Done()
			for r := lo; r < hi; r++ {
				out[r] = closestDistance(plan, src, syn, r)
			}
		}(lo, hi)
	}
	wg.Wait()
	return out
}

// closestDistance is sampled row r's distance to its closest source row.
// The per-column terms are summed in column order and the smallest SUM
// divided once by the column count; a partial sum already at or past the
// best is abandoned (every term is non-negative, so it cannot win).
func closestDistance(plan *disclosurePlan, src, syn *disclosureRows, r int) float64 {
	ncols := len(plan.cols)
	sv := syn.vals[r*plan.slots : (r+1)*plan.slots]
	sn := syn.nulls[r*ncols : (r+1)*ncols]
	ss := syn.sets[r*plan.sets : (r+1)*plan.sets]
	best := math.Inf(1)
	for q := 0; q < src.n && best > 0; q++ {
		qv := src.vals[q*plan.slots : (q+1)*plan.slots]
		qn := src.nulls[q*ncols : (q+1)*ncols]
		qs := src.sets[q*plan.sets : (q+1)*plan.sets]
		sum := 0.0
		for ci := 0; ci < ncols && sum < best; ci++ {
			c := &plan.cols[ci]
			if sn[ci] || qn[ci] {
				if sn[ci] != qn[ci] {
					sum += 1
				}
				continue
			}
			switch c.kind {
			case disclosureNominal:
				if sv[c.slot] != qv[c.slot] {
					sum += 1
				}
			case disclosureSet:
				sum += jaccardDistance(ss[c.set], qs[c.set])
			case disclosureVector:
				el := 0.0
				for s := c.slot; s < c.slot+c.width; s++ {
					el += numericDistance(sv[s], qv[s], plan.ranges[s])
				}
				sum += el / float64(c.width)
			default:
				sum += numericDistance(sv[c.slot], qv[c.slot], plan.ranges[c.slot])
			}
		}
		if sum < best {
			best = sum
		}
	}
	if ncols == 0 {
		return 0
	}
	return best / float64(ncols)
}

// disclosureQuantile is the type-7 quantile of sorted (ascending,
// non-empty). The product is barriered so it cannot fuse into the add.
func disclosureQuantile(sorted []float64, q float64) float64 {
	n := len(sorted)
	if n == 1 {
		return sorted[0]
	}
	h := float64(float64(n-1) * q)
	lo := int(h)
	if lo >= n-1 {
		return sorted[n-1]
	}
	frac := h - float64(lo)
	return sorted[lo] + float64((sorted[lo+1]-sorted[lo])*frac)
}

// disclosureSampleOrdinals picks min(n, sample) distinct generated-row
// ordinals in [0, n), ascending: every row when n fits, else Floyd's
// algorithm over the disclosure stream — a pure function of (n, sample,
// seed) that never touches the generation RNG.
func disclosureSampleOrdinals(n, sample int, seed int64) []int {
	if n <= sample {
		out := make([]int, n)
		for i := range out {
			out[i] = i
		}
		return out
	}
	key := drawStreamKey(seed, disclosureSampleDomain)
	chosen := make(map[int]struct{}, sample)
	out := make([]int, 0, sample)
	for j := n - sample; j < n; j++ {
		h := splitmix64(key ^ uint64(j))
		hi, _ := bits.Mul64(h, uint64(j+1))
		t := int(hi)
		if _, dup := chosen[t]; dup {
			t = j
		}
		chosen[t] = struct{}{}
		out = append(out, t)
	}
	sort.Ints(out)
	return out
}
