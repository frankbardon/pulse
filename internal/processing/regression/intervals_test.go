var mmmLikePredictors = []string{"tv", "search", "holiday", "week", "rB", "rC", "rD"}

func mmmLikeRecords() []Record {
	out := make([]Record, len(mmmLikeRows))
	for i, r := range mmmLikeRows {
		m := map[string]float64{"rev": r[0]}
		for j, name := range mmmLikePredictors {
			m[name] = r[j+1]
		}
		out[i] = mockRecord{values: m}
	}
	return out
}

func ciRelNear(got, want, tol float64) bool {
	return math.Abs(got-want) <= tol*math.Max(1, math.Abs(want))
}

// TestRegressionCI_FixtureLikeMatchesR: REG_OLS intervals on the
// media-mix-shaped design are R's confint(lm(rev ~ tv + search + holiday
// + week + rB + rC + rD)) at 0.95 (the default) and 0.90 — Student t on
// the residual df 52, not the normal 1.96 (which would give a lower
// intercept bound of 90.8384 against R's 90.5586).
func TestRegressionCI_FixtureLikeMatchesR(t *testing.T) {
	// R 4.6.1: confint(fit, level = lv); df.residual(fit) = 52.
	cases := []struct {
		level        float64
		lower, upper []float64
	}{
		{0, // unset: the 0.95 default
			[]float64{90.558601172372619, 7.0999092674232385, 7.4847897841231648, 20.367740504895792, -0.096172036856036092, 13.076926386210555, -21.012349413865969, -1.1960531209735161},
			[]float64{114.63177482356235, 10.776835840543438, 13.701808990653404, 29.845488490962047, 0.65187934832516459, 22.190868637832342, -11.75502009798624, 8.3505067089460958}},
		{0.9,
			[]float64{92.549802156344185, 7.4040444810213142, 7.999027538595616, 21.151687872581441, -0.034297326200239786, 13.83078173749252, -20.246633870505629, -0.40641401470885619},
			[]float64{112.64057383959079, 10.472700626945363, 13.187571236180954, 29.061541123276399, 0.59000463766936817, 21.437013286550375, -12.520735641346583, 7.5608676026814354}},
	}
	keys := append([]string{InterceptKey}, mmmLikePredictors...)
	for _, c := range cases {
		spec := &types.RegressionSpec{Type: types.REG_OLS, Target: "rev", Predictors: mmmLikePredictors, ConfLevel: c.level}
		res, err := FitBuffered([]*types.RegressionSpec{spec}, schemaWithFields(append([]string{"rev"}, mmmLikePredictors...)...), mmmLikeRecords())
		if err != nil {
			t.Fatal(err)
		}
		r := res[0]
		wantLevel := c.level
		if wantLevel == 0 {
			wantLevel = 0.95
		}
		if r.DF != 52 || r.ConfLevel != wantLevel {
			t.Errorf("level %v: df %v conf_level %v, want 52 / %v", c.level, r.DF, r.ConfLevel, wantLevel)
		}
		for i, k := range keys {
			if !ciRelNear(r.CILower[k], c.lower[i], 1e-10) || !ciRelNear(r.CIUpper[k], c.upper[i], 1e-10) {
				t.Errorf("level %v %s: [%.17g, %.17g], R [%.17g, %.17g]", c.level, k, r.CILower[k], r.CIUpper[k], c.lower[i], c.upper[i])
			}
		}
	}
}

func fitOne(t *testing.T, spec *types.RegressionSpec, recs []Record) *types.RegressionResult {
	t.Helper()
	res, err := FitBuffered([]*types.RegressionSpec{spec}, schemaWithFields(append([]string{spec.Target}, spec.Predictors...)...), recs)
	if err != nil {
		t.Fatalf("%+v: %v", spec, err)
	}
	return res[0]
}

func sortedKeys(m map[string]float64) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

// TestRegressionCI_PresentExactlyWhereStdErrors: every fit path carries
// an interval for exactly the keys its std_errors map carries — the full
// set on ridge and under Selection (keyed by the selected predictors),
// only the kept predictors on lasso (no intercept), none at all (and no
// conf_level) on a fit with no standard error. Every bound is
// coefficient ∓ q·SE with one q per fit.
func TestRegressionCI_PresentExactlyWhereStdErrors(t *testing.T) {
	recs := mmmLikeRecords()
	specs := map[string]*types.RegressionSpec{
		"ols":       {Type: types.REG_OLS, Target: "rev", Predictors: mmmLikePredictors},
		"ridge":     {Type: types.REG_OLS, Target: "rev", Predictors: mmmLikePredictors, Penalty: "l2", Alpha: 0.5},
		"lasso":     {Type: types.REG_OLS, Target: "rev", Predictors: mmmLikePredictors, Penalty: "l1", Alpha: 3},
		"selection": {Type: types.REG_OLS, Target: "rev", Predictors: mmmLikePredictors, Selection: "backward", Criterion: "bic"},
	}
	for name, spec := range specs {
		r := fitOne(t, spec, recs)
		if len(r.StdErrors) == 0 {
			t.Fatalf("%s: no std errors", name)
		}
		if got, want := sortedKeys(r.CILower), sortedKeys(r.StdErrors); !slices.Equal(got, want) {
			t.Errorf("%s: ci_lower keys %v, std_errors keys %v", name, got, want)
		}
		if got, want := sortedKeys(r.CIUpper), sortedKeys(r.StdErrors); !slices.Equal(got, want) {
			t.Errorf("%s: ci_upper keys %v, std_errors keys %v", name, got, want)
		}
		if r.ConfLevel != 0.95 || !(r.DF > 0) {
			t.Errorf("%s: conf_level %v df %v", name, r.ConfLevel, r.DF)
		}
		q := -1.0
		for k, se := range r.StdErrors {
			if se == 0 {
				continue
			}
			qk := (r.CIUpper[k] - r.CILower[k]) / (2 * se)
			if q < 0 {
				q = qk
			} else if !ciRelNear(qk, q, 1e-9) {
				t.Errorf("%s %s: critical value %v, others %v", name, k, qk, q)
			}
			if mid := (r.CIUpper[k] + r.CILower[k]) / 2; !ciRelNear(mid, r.Coefficients[k], 1e-9) {
				t.Errorf("%s %s: interval centre %v, coefficient %v", name, k, mid, r.Coefficients[k])
			}
		}
		switch name {
		case "lasso":
			if _, ok := r.CILower[InterceptKey]; ok {
				t.Errorf("lasso carries an intercept interval with no intercept std error")
			}
			if len(r.CILower) == len(mmmLikePredictors)+1 {
				t.Errorf("lasso: alpha 3 should drop at least one predictor; got intervals for all %d", len(r.CILower))
			}
		case "selection":
			if len(r.CILower) != len(r.SelectedFeatures)+1 {
				t.Errorf("selection: %d intervals for %d selected + intercept", len(r.CILower), len(r.SelectedFeatures))
			}
		}
	}

	// A GLM whose selection keeps no predictor reports no standard error:
	// no intervals, no conf_level.
	empty := &types.RegressionResult{Coefficients: map[string]float64{InterceptKey: 1}, StdErrors: map[string]float64{}}
	attachIntervals(empty, 0.95, 0, false)
	if empty.CILower != nil || empty.CIUpper != nil || empty.ConfLevel != 0 || empty.DF != 0 {
		t.Errorf("no std errors → no interval fields; got %+v", empty)
	}
}

// TestRegressionCI_ResampleIsWaldOnResampledSE: under Resample the
// intervals are coefficient ∓ z·SE on the RESAMPLED standard errors, the
// basis the resample p-values use; df is absent.
func TestRegressionCI_ResampleIsWaldOnResampledSE(t *testing.T) {
	spec := &types.RegressionSpec{Type: types.REG_OLS, Target: "rev", Predictors: mmmLikePredictors, Resample: "jackknife", ConfLevel: 0.9}
	r := fitOne(t, spec, mmmLikeRecords())
	if r.DF != 0 || r.ConfLevel != 0.9 {
		t.Errorf("df %v conf_level %v, want absent / 0.9", r.DF, r.ConfLevel)
	}
	// R: qnorm(0.95)
	const z = 1.6448536269514722
	for k, se := range r.StdErrors {
		want := r.Coefficients[k] - z*se
		if !ciRelNear(r.CILower[k], want, 1e-12) || !ciRelNear(r.CIUpper[k], r.Coefficients[k]+z*se, 1e-12) {
			t.Errorf("%s: [%v, %v], want β ∓ z·SE_jackknife with SE %v", k, r.CILower[k], r.CIUpper[k], se)
		}
	}
}

// TestRegressionCI_BayesMirrorsCredibleIntervals: REG_BAYES_LINEAR's
// intervals are its credible_intervals bit for bit at the same level —
// credible_level when conf_level is unset — and conf_level alone moves
// them (credible_intervals stay at credible_level). df is 2·a_n.
func TestRegressionCI_BayesMirrorsCredibleIntervals(t *testing.T) {
	recs := mmmLikeRecords()
	for _, s := range []types.RegressionSpec{
		{Type: types.REG_BAYES_LINEAR, Target: "rev", Predictors: mmmLikePredictors},
		{Type: types.REG_BAYES_LINEAR, Target: "rev", Predictors: mmmLikePredictors, CredibleLevel: 0.8},
		{Type: types.REG_BAYES_LINEAR, Target: "rev", Predictors: mmmLikePredictors, ConfLevel: 0.8, CredibleLevel: 0.8},
	} {
		r := fitOne(t, &s, recs)
		want := s.CredibleLevel
		if want == 0 {
			want = 0.95
		}
		if r.ConfLevel != want {
			t.Errorf("credible_level %v: conf_level %v, want %v", s.CredibleLevel, r.ConfLevel, want)
		}
		if aN := defaultBayesPriorShape + float64(len(recs))/2; r.DF != 2*aN {
			t.Errorf("df %v, want 2·a_n = %v", r.DF, 2*aN)
		}
		for k, ci := range r.CredibleIntervals {
			if r.CILower[k] != ci[0] || r.CIUpper[k] != ci[1] {
				t.Errorf("credible_level %v %s: ci [%v, %v] != credible %v", s.CredibleLevel, k, r.CILower[k], r.CIUpper[k], ci)
			}
		}
	}
	s := types.RegressionSpec{Type: types.REG_BAYES_LINEAR, Target: "rev", Predictors: mmmLikePredictors, ConfLevel: 0.5}
	r := fitOne(t, &s, recs)
	for k, ci := range r.CredibleIntervals {
		if !(r.CILower[k] > ci[0] && r.CIUpper[k] < ci[1]) {
			t.Errorf("%s: a 0.5 interval [%v, %v] must sit inside the 0.95 credible interval %v", k, r.CILower[k], r.CIUpper[k], ci)
		}
	}
}

// TestRegressionCI_ConfLevelValidated: conf_level outside (0, 1) is
// PROCESSING_CONFIG on every family; zero is the default.
func TestRegressionCI_ConfLevelValidated(t *testing.T) {
	for _, typ := range types.AllRegressionTypes() {
		for _, c := range []float64{-0.1, 1, 1.5, math.NaN()} {
			spec := &types.RegressionSpec{Type: typ, Target: "y", Predictors: []string{"x"}, ConfLevel: c}
			if typ == types.REG_GLM {
				spec.Family = "binomial"
			}
			err := ValidateRegression(spec)
			var ce *errors.CodedError
			if ce = asCoded(err); ce == nil || ce.Code != errors.PROCESSING_CONFIG {
				t.Errorf("%s conf_level %v: err %v, want PROCESSING_CONFIG", typ, c, err)
			}
		}
		spec := &types.RegressionSpec{Type: typ, Target: "y", Predictors: []string{"x"}, ConfLevel: 0.99}
		if typ == types.REG_GLM {
			spec.Family = "binomial"
		}
		if err := ValidateRegression(spec); err != nil {
			t.Errorf("%s conf_level 0.99: %v", typ, err)
		}
	}
}

func asCoded(err error) *errors.CodedError {
	ce, _ := err.(*errors.CodedError)
	return ce
}

// TestRegressionCI_UndefinedIsNull: df ≤ 0 leaves every bound and df
// undefined, and the wire carries them as null (MarshalFinite), never 0.
func TestRegressionCI_UndefinedIsNull(t *testing.T) {
	r := &types.RegressionResult{
		Type:         types.REG_OLS,
		Coefficients: map[string]float64{InterceptKey: 2, "x": 1},
		StdErrors:    map[string]float64{InterceptKey: 0, "x": 0.5},
	}
	attachIntervals(r, 0.95, -1.5, true)
	for k := range r.StdErrors {
		if !math.IsNaN(r.CILower[k]) || !math.IsNaN(r.CIUpper[k]) {
			t.Errorf("%s: [%v, %v], want NaN on df ≤ 0", k, r.CILower[k], r.CIUpper[k])
		}
	}
	raw, err := json.Marshal(r)
	if err != nil {
		t.Fatal(err)
	}
	for _, frag := range []string{
		`"ci_lower":{"(intercept)":null,"x":null}`,
		`"ci_upper":{"(intercept)":null,"x":null}`,
		`"df":null`,
		`"conf_level":0.95`,
	} {
		if !strings.Contains(string(raw), frag) {
			t.Errorf("wire %s lacks %s", raw, frag)
		}
	}
}

// TestRegressionCI_InterceptOnlySelection: a Selection that keeps no
// predictor reports the intercept-only fit, whose interval is the
// one-sample t interval on n − 1 df — R 4.6.1:
//
//	y <- c(4.1, 5.3, 3.8, 4.9, 5.6, 4.4, 3.9, 5.1, 4.7, 4.2, 5.0, 4.6)
//	x <- c(1, 7, 3, 9, 2, 8, 4, 6, 5, 11, 10, 12)
//	step(lm(y ~ x), k = log(12))       # → y ~ 1
//	t.test(y, conf.level = 0.9)$conf.int
func TestRegressionCI_InterceptOnlySelection(t *testing.T) {
	y := []float64{4.1, 5.3, 3.8, 4.9, 5.6, 4.4, 3.9, 5.1, 4.7, 4.2, 5.0, 4.6}
	x := []float64{1, 7, 3, 9, 2, 8, 4, 6, 5, 11, 10, 12}
	recs := make([]Record, len(y))
	for i := range y {
		recs[i] = mockRecord{values: map[string]float64{"y": y[i], "x": x[i]}}
	}
	spec := &types.RegressionSpec{Type: types.REG_OLS, Target: "y", Predictors: []string{"x"}, Selection: "backward", Criterion: "bic", ConfLevel: 0.9}
	r := fitOne(t, spec, recs)
	if len(r.SelectedFeatures) != 0 {
		t.Fatalf("selection kept %v, want none", r.SelectedFeatures)
	}
	if r.DF != 11 || r.ConfLevel != 0.9 {
		t.Errorf("df %v conf_level %v, want 11 / 0.9", r.DF, r.ConfLevel)
	}
	if lo, hi := r.CILower[InterceptKey], r.CIUpper[InterceptKey]; !ciRelNear(lo, 4.3381289681605733, 1e-10) || !ciRelNear(hi, 4.9285376985060925, 1e-10) {
		t.Errorf("intercept interval [%.17g, %.17g], R [4.3381289681605733, 4.9285376985060925]", lo, hi)
	}
}
