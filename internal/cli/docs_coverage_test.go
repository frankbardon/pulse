// The documentation coverage gates live here because the matrix's CLI rows
// come from the tree App builds, and only internal/cli (and cmd/pulse) may
// reach the CLI framework: internal/doccoverage takes the tree as data.
// `make docs` regenerates the page by running TestDocsCoverageCurrent with
// -update-coverage.
var updateCoverage = flag.Bool("update-coverage", false, "rewrite docs/src/contract/coverage.md (prefer `make docs`)")

// coverageRepoRoot is the module root as reached from this package.
const coverageRepoRoot = "../.."

// docsCoverageEnv are the variables `make docs` clears so a developer's
// .env cannot perturb the generated pages (the Makefile's DOCS_GUIDE_ENV).
var docsCoverageEnv = []string{"PULSE_LABEL_TABLES_DIR", "PULSE_RANGE_TABLES_DIR", "PULSE_LOOKUP_TABLES_DIR",
	"PULSE_POPULATIONS_DIR", "PULSE_TEMPLATES_DIR", "PULSE_FEATURE_PROFILE"}

// coverageSurface flattens the tree after urfave's setup (one --help run,
// so the framework's help flag and completion command are mounted as the
// binary mounts them). urfave's help commands are skipped.
func coverageSurface(root *cli.Command) doccoverage.CLISurface {
	root.Writer, root.ErrWriter = io.Discard, io.Discard
	_ = root.Run(context.Background(), []string{root.Name, "--help"})
	var s doccoverage.CLISurface
	var visit func(path []string, c *cli.Command)
	visit = func(path []string, c *cli.Command) {
		s.Commands = append(s.Commands, doccoverage.CLICommand{
			Path: strings.Join(path, " "), Runnable: c.Action != nil, Usage: c.Usage,
			Text: []string{c.UsageText, c.Description, c.ArgsUsage},
		})
		for _, f := range c.Flags {
			usage := ""
			if u, ok := f.(interface{ GetUsage() string }); ok {
				usage = u.GetUsage()
			}
			s.Flags = append(s.Flags, doccoverage.CLIFlag{Names: f.Names(), Usage: usage, Help: f.String()})
		}
		for _, sub := range c.Commands {
			if sub.Name != "help" {
				visit(append(append([]string(nil), path...), sub.Name), sub)
			}
		}
	}
	visit([]string{root.Name}, root)
	return s
}

// docsCoverage builds the matrix once per test binary: both gates read the
// same build (each clears the environment first, so whichever runs first
// builds it under the `make docs` environment).
var docsCoverage struct {
	once sync.Once
	m    *doccoverage.Matrix
	err  error
}

func buildDocsCoverage(t *testing.T) *doccoverage.Matrix {
	t.Helper()
	for _, k := range docsCoverageEnv {
		t.Setenv(k, "")
	}
	docsCoverage.once.Do(func() {
		fsys := afero.NewReadOnlyFs(afero.NewBasePathFs(afero.NewOsFs(), coverageRepoRoot))
		docsCoverage.m, docsCoverage.err = doccoverage.BuildFrom(fsys, coverageSurface(App()))
	})
	if docsCoverage.err != nil {
		t.Fatal(docsCoverage.err)
	}
	return docsCoverage.m
}

// TestDocsCoverageCurrent keeps the generated coverage matrix
// (docs/src/contract/coverage.md) current: it rebuilds the page from the
// sources of truth and requires the committed page to match byte for byte.
// A new public symbol, leaf, flag, tool, operator, code or env var — or a
// doc edit that changes a cell — without `make docs` fails here.
// -update-coverage rewrites the page instead (`make docs` runs it so).
func TestDocsCoverageCurrent(t *testing.T) {
	// serial: t.Setenv mutates the process environment
	want := buildDocsCoverage(t).Render()
	osfs := afero.NewBasePathFs(afero.NewOsFs(), coverageRepoRoot)
	if *updateCoverage {
		if err := afero.WriteFile(osfs, doccoverage.PagePath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := afero.ReadFile(osfs, doccoverage.PagePath)
	if err != nil {
		t.Fatalf("%v: run `make docs` and commit %s", err, doccoverage.PagePath)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale: run `make docs` and commit it (never hand-edit it; it is generated by internal/doccoverage)", doccoverage.PagePath)
	}
}

// TestDocsCoverageNoGaps fails on a required coverage cell that is empty
// (a gap) unless the shrink-only allowlist
// internal/doccheck/allowlists/coverage.txt names it, and on an allowlist
// entry whose gap has been closed. Keys are (row kind, "<identifier>
// <surface>").
func TestDocsCoverageNoGaps(t *testing.T) {
	// serial: t.Setenv mutates the process environment
	m := buildDocsCoverage(t)
	if len(m.Lines) < 1000 {
		t.Fatalf("only %d coverage rows — a source is broken", len(m.Lines))
	}
	allow, err := doccheck.Load(afero.NewBasePathFs(afero.NewOsFs(), coverageRepoRoot), doccheck.AllowlistFile(doccoverage.AllowlistName))
	if err != nil {
		t.Fatal(err)
	}
	for _, p := range allow.Reconcile(m.Gaps()).Problems(allow.File) {
		t.Error(p)
	}
}

// TestCoverageSurfaceFlattensTree: the flattened surface carries the
// runnable leaves, every flag mount with its usage, and the env-var
// sources in the help lines.
func TestCoverageSurfaceFlattensTree(t *testing.T) {
	t.Parallel()
	s := coverageSurface(App())
	leaves, flags := map[string]bool{}, map[string]bool{}
	for _, c := range s.Commands {
		if c.Runnable {
			leaves[c.Path] = true
		}
	}
	help := ""
	for _, f := range s.Flags {
		for _, n := range f.Names {
			flags[n] = true
		}
		help += f.Help
	}
	for _, want := range []string{"pulse cohort inspect", "pulse completion bash"} {
		if !leaves[want] {
			t.Errorf("leaf %q missing from the surface", want)
		}
	}
	for _, want := range []string{"json", "help", "h"} {
		if !flags[want] {
			t.Errorf("flag %q missing from the surface", want)
		}
	}
	if !strings.Contains(help, "PULSE_DATA_DIR") {
		t.Error("flag help lines lack their env-var sources")
	}
}
