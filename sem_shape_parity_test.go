// sem_shape_parity_test.go fits the synthetic same-shape SEM models
// (sem-contribution E2-S5; internal/sem/testdata shape63_model.txt,
// shape89_model.txt over shape_data.csv, gen_shape_data.py) in ONE
// request that uses every sem-contribution piece at once: a computed
// member (a formula attribute; E2-S2), vector z-scoring over the
// listwise rows (E2-S1), the default singular "nearest" on an n < p
// battery (E2-S3) beside non-singular ones, and the records encoding
// (E2-S4) — every figure read from the records wire form. MAT_SEM's
// defaults are semopy 2.3.11's: the default setup is pinned to
// semopy's default fit, ftol 1e-14 to its tight fit
// (fit_semopy_shape.py, regenerated by gen_semopy.sh outside CI).

const shapeTestdata = "internal/sem/testdata/"

// This shape's tolerances against semopy's default and tight fits (see
// TestSEMShape_OneRequestMatchesSemopy for the measurements).
const (
	shapeDefaultTol = 1e-8
	shapeTightTol   = 5e-6
)

// shapeSemopy is a fit_semopy_shape.py reference.
type shapeSemopy struct {
	Fun     float64            `json:"fun"`
	NIter   float64            `json:"n_iter"`
	N       float64            `json:"n"`
	P       int                `json:"p"`
	Nearest bool               `json:"nearest"`
	MinEig  float64            `json:"min_eigenvalue"`
	Stats   map[string]float64 `json:"stats"`
	Params  []struct {
		LVal string   `json:"lval"`
		Op   string   `json:"op"`
		RVal string   `json:"rval"`
		Est  float64  `json:"est"`
		Std  *float64 `json:"std"`
		SE   *float64 `json:"se"`
		Z    *float64 `json:"z"`
		P    *float64 `json:"p"`
	} `json:"params"`
}

// shapeCohort writes shape_data.csv as a cohort. x01 is stored
// reverse-coded (x01r = 1 − x01) so the model's x01 exists only as the
// request's formula attribute; x05 and y2 keep their blank cells as
// nulls.
func shapeCohort(t *testing.T) *Pulse {
	t.Helper()
	f, err := os.Open(shapeTestdata + "shape_data.csv")
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	recs, err := csv.NewReader(f).ReadAll()
	if err != nil {
		t.Fatal(err)
	}
	header := recs[0]
	fields := make([]encoding.Field, len(header))
	for i, h := range header {
		switch h {
		case "id":
			fields[i] = encoding.Field{Name: h, Type: encoding.FieldTypeU32, Description: "Synthetic row identifier"}
		case "x01":
			fields[i] = encoding.Field{Name: "x01r", Type: encoding.FieldTypeF64, Description: "Synthetic 0/1 item, reverse coded"}
		default:
			fields[i] = encoding.Field{Name: h, Type: encoding.FieldTypeF64, Nullable: h == "x05" || h == "y2", Description: "Synthetic item " + h}
		}
	}
	fsys := afero.NewMemMapFs()
	p, err := New(Options{FS: fsys})
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	b, err := p.NewCohortBuilder(ctx, "shape.pulse", encoding.Schema{Fields: fields}, CohortBuilderOptions{})
	if err != nil {
		t.Fatal(err)
	}
	for _, rec := range recs[1:] {
		row := make(CohortRow, len(rec))
		for i, s := range rec {
			if s == "" {
				continue // nil: a null cell
			}
			v, err := strconv.ParseFloat(s, 64)
			if err != nil {
				t.Fatal(err)
			}
			switch header[i] {
			case "id":
				row[i] = uint64(v)
			case "x01":
				row[i] = 1 - v
			default:
				row[i] = v
			}
		}
		if err := b.Append(row); err != nil {
			t.Fatal(err)
		}
	}
	if _, err := b.Close(); err != nil {
		t.Fatal(err)
	}
	return p
}

// shapeMembers is the model's indicators then outputs, x01..xNN, y1..y4.
func shapeMembers(n int) []string {
	out := make([]string, 0, n+4)
	for i := 1; i <= n; i++ {
		out = append(out, "x"+leftPad2(i))
	}
	return append(out, "y1", "y2", "y3", "y4")
}

func leftPad2(i int) string {
	if i < 10 {
		return "0" + strconv.Itoa(i)
	}
	return strconv.Itoa(i)
}

// TestSEMShape_OneRequestMatchesSemopy: one request, six MAT_SEM slots
// (63 and 89 indicators over every row, and the 63 model over ids < 50,
// n = 47 < p = 67; each at the defaults and at ftol 1e-14), every slot
// in records encoding over a z-scored vector whose x01 is a formula
// attribute (the singular vector's x01s, null outside its rows, is
// labelled x01 so the same model text names it). The non-singular slots
// fit raw with no warning; the n < p slots fit semopy's cov_nearest
// substitute and warn PULSE_MATRIX_NEAREST_PD.
//
// Tolerances are this shape's, set explicitly (shapeDefaultTol,
// shapeTightTol). The 0/1 battery's objective is flat along a
// first-order factor's scale — its loadings move together against its
// construct path and its small latent variance; the expected
// information's smallest eigenvalue is ~11 against ~1e4 at full n
// (~0.7 against ~1.7e3 at n < p). Two consequences, measured: (1) the
// default ftol 1e-6 stop lies ~1e-3 (relative) short of the optimum
// along that direction, yet MAT_SEM reproduces semopy's stopping
// iterate — same iteration count, every figure within 4e-10 — so the
// default pin is 1e-8, not the 1e-4 near_* needs; (2) at ftol 1e-14
// the optimum is resolved along it only to ~sqrt(eps·F/h) ≈ 1e-7..1e-6
// (estimates up to 9e-7 apart, iteration counts differ by up to five),
// so the tight pin is 5e-6. semopy varies on its own at both levels:
// two runs of fit_semopy_shape.py (Python set order differs per
// process) differ by up to 3e-10 at the default and 3e-7 tight.
// internal/sem TestFit_ShapeMatchesSemopy pins the default fits from
// the rows' own S.
func TestSEMShape_OneRequestMatchesSemopy(t *testing.T) {
	p := shapeCohort(t)
	models := map[int]string{}
	for _, n := range []int{63, 89} {
		b, err := os.ReadFile(shapeTestdata + "shape" + strconv.Itoa(n) + "_model.txt")
		if err != nil {
			t.Fatal(err)
		}
		models[n] = string(b)
	}
	m63, m89 := shapeMembers(63), shapeMembers(89)
	sing := append([]string{"x01s"}, m63[1:]...)
	z := types.VectorStandardizeZScore
	req := &types.Request{
		Cohort: &types.Cohort{Filename: "shape.pulse"},
		Attributes: []*types.Attribute{
			{Type: types.ATTR_FORMULA, Label: "x01", Expression: "1 - x01r"},
			{Type: types.ATTR_FORMULA, Label: "x01s", Expression: "id < 50 ? 1 - x01r : nil"},
		},
		Vectors: []types.VectorSpec{
			{Name: "v63", Fields: m63, Standardize: z},
			{Name: "v89", Fields: m89, Standardize: z},
			{Name: "v63s", Fields: sing, Labels: m63, Standardize: z},
		},
	}
	type slot struct {
		name, vector, ref string
		model             int
		tight             bool
	}
	var slots []slot
	for _, s := range []struct {
		vector, ref string
		model       int
	}{{"v63", "shape63", 63}, {"v89", "shape89", 89}, {"v63s", "shape63_singular", 63}} {
		slots = append(slots, slot{s.ref, s.vector, s.ref, s.model, false}, slot{s.ref + "_tight", s.vector, s.ref, s.model, true})
	}
	for _, s := range slots {
		params := map[string]any{"model": models[s.model]}
		if s.tight {
			params["ftol"], params["max_iter"] = 1e-14, 100000
		}
		raw, err := json.Marshal(params)
		if err != nil {
			t.Fatal(err)
		}
		req.Matrices = append(req.Matrices, types.MatrixSpec{Name: s.name, Type: types.MAT_SEM, Vector: s.vector, Params: raw, Encoding: types.MatrixEncodingRecords})
	}
	resp, err := p.Process(context.Background(), req)
	if err != nil {
		t.Fatalf("Process: %v", err)
	}
	if len(resp.Matrices) != len(slots) {
		t.Fatalf("%d matrices, want %d", len(resp.Matrices), len(slots))
	}
	for i, s := range slots {
		res := resp.Matrices[i]
		t.Run(s.name, func(t *testing.T) {
			kind, tol := "default", shapeDefaultTol
			if s.tight {
				kind, tol = "tight", shapeTightTol
			}
			rb, err := os.ReadFile(shapeTestdata + s.ref + "_semopy_" + kind + ".json")
			if err != nil {
				t.Fatal(err)
			}
			var ref shapeSemopy
			if err := json.Unmarshal(rb, &ref); err != nil {
				t.Fatal(err)
			}
			if res.Name != s.name || res.Error != nil {
				t.Fatalf("%s: error %+v", res.Name, res.Error)
			}
			if res.Scalars["n"] != ref.N || res.Scalars["converged"] != 1 {
				t.Fatalf("n %v converged %v, semopy n %v", res.Scalars["n"], res.Scalars["converged"], ref.N)
			}
			if !s.tight && res.Scalars["iterations"] != ref.NIter {
				t.Errorf("iterations %v, semopy's default stop %v", res.Scalars["iterations"], ref.NIter)
			}
			// P3: only the n < p slots substitute, as semopy does.
			var codes []string
			for _, w := range res.Warnings {
				codes = append(codes, w.Code)
			}
			if ref.Nearest {
				if len(res.Warnings) != 1 || res.Warnings[0].Code != string(perr.PULSE_MATRIX_NEAREST_PD) {
					t.Fatalf("warnings %v, want PULSE_MATRIX_NEAREST_PD only", codes)
				}
				d := res.Warnings[0].Details
				if d["n"] != ref.N || d["p"] != ref.P {
					t.Errorf("nearest details %v, want n %v p %v", d, ref.N, ref.P)
				}
				if me, _ := d["min_eigenvalue"].(float64); math.Abs(me-ref.MinEig) > 1e-12 {
					t.Errorf("min_eigenvalue %v, semopy's input %v", d["min_eigenvalue"], ref.MinEig)
				}
			} else if len(res.Warnings) != 0 {
				t.Fatalf("warnings %v, want none (S factors)", codes)
			}
			checkShapeRecords(t, res, ref, tol)
		})
	}
}

// checkShapeRecords reads the estimates from the records wire form
// (lval / op / rval / parameter / free beside each row's cells) and
// pins them, the fit statistics and the objective to semopy.
func checkShapeRecords(t *testing.T, res types.MatrixResult, ref shapeSemopy, tol float64) {
	t.Helper()
	wire, err := json.Marshal(res)
	if err != nil {
		t.Fatal(err)
	}
	var w struct {
		Auxiliary map[string]struct {
			Encoding string           `json:"encoding"`
			Columns  []string         `json:"columns"`
			Rows     []map[string]any `json:"rows"`
		} `json:"auxiliary"`
	}
	if err := json.Unmarshal(wire, &w); err != nil {
		t.Fatal(err)
	}
	est := w.Auxiliary["estimates"]
	if est.Encoding != string(types.MatrixEncodingRecords) || strings.Join(est.Columns, ",") != "estimate,std_estimate,std_err,z_value,p_value" {
		t.Fatalf("estimates wire encoding %q columns %v", est.Encoding, est.Columns)
	}
	if len(est.Rows) != len(ref.Params) {
		t.Errorf("%d estimate records, semopy has %d", len(est.Rows), len(ref.Params))
	}
	got := map[string]map[string]any{}
	params := map[string]bool{}
	for _, r := range est.Rows {
		lv, _ := r["lval"].(string)
		op, _ := r["op"].(string)
		rv, _ := r["rval"].(string)
		key := lv + " " + op + " " + rv
		if r["key"] != key {
			t.Errorf("record key %v, lval/op/rval %q", r["key"], key)
		}
		free, ok := r["free"].(bool)
		name, _ := r["parameter"].(string)
		if !ok || (free && name == "") {
			t.Errorf("%s: free %v parameter %q", key, r["free"], name)
		}
		if free {
			params[name] = true
		}
		got[key] = r
	}
	if float64(len(params)) != res.Scalars["n_params"] {
		t.Errorf("%d distinct free parameters in the records, n_params %v", len(params), res.Scalars["n_params"])
	}
	num := func(r map[string]any, c string) (float64, bool) {
		v, ok := r[c].(float64)
		return v, ok
	}
	rel := func(a, b float64) float64 { return math.Abs(a-b) / math.Max(1, math.Abs(b)) }
	for _, sp := range ref.Params {
		k := sp.LVal + " " + sp.Op + " " + sp.RVal
		r, ok := got[k]
		if !ok && sp.Op == "~~" {
			r, ok = got[sp.RVal+" ~~ "+sp.LVal] // semopy orients exogenous-latent pairs by Python set order
		}
		if !ok {
			t.Errorf("missing record %q", k)
			continue
		}
		near := func(c string, want, tol float64) {
			g, ok := num(r, c)
			if d := rel(g, want); !ok || !(d <= tol) {
				t.Errorf("%s %s = %v, semopy %.12g (rel %.1e)", k, c, r[c], want, d)
			}
		}
		near("estimate", sp.Est, tol)
		if sp.Std != nil {
			near("std_estimate", *sp.Std, tol)
		}
		if sp.SE == nil {
			if r["std_err"] != nil || r["free"] != false {
				t.Errorf("%s: fixed in semopy, record std_err %v free %v", k, r["std_err"], r["free"])
			}
			continue
		}
		if r["free"] != true {
			t.Errorf("%s: free in semopy, record free %v", k, r["free"])
		}
		near("std_err", *sp.SE, tol)
		near("z_value", *sp.Z, 2*tol)
		if g, ok := num(r, "p_value"); !ok || !(math.Abs(g-*sp.P) <= tol) {
			t.Errorf("%s p_value = %v, semopy %g", k, r["p_value"], *sp.P)
		}
	}
	for sk, pk := range map[string]string{
		"DoF": "dof", "DoF Baseline": "dof_baseline", "chi2": "chi2", "chi2 p-value": "chi2_p_value",
		"chi2 Baseline": "chi2_baseline", "CFI": "cfi", "GFI": "gfi", "AGFI": "agfi", "NFI": "nfi",
		"TLI": "tli", "RMSEA": "rmsea", "AIC": "aic", "BIC": "bic", "LogLik": "loglik",
	} {
		if d := rel(res.Scalars[pk], ref.Stats[sk]); !(d <= tol) {
			t.Errorf("%s = %.12g, semopy %.12g", pk, res.Scalars[pk], ref.Stats[sk])
		}
	}
	if d := rel(res.Scalars["objective"], ref.Fun); !(d <= tol) {
		t.Errorf("objective %.14g, semopy %.14g", res.Scalars["objective"], ref.Fun)
	}
}
